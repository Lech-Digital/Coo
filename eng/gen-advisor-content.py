#!/usr/bin/env python3
"""Turns the Advisor's age guide (src/Mobile/Coo.Mobile.Presentation/Advisor/Content/*.json, one file per language, the
place to edit and translate) into C# data, so the Presentation layer never parses JSON (Spec 003 §9: only Coo.Codecs
and Coo.Contracts touch JSON). Run after editing a file: python3 eng/gen-advisor-content.py
AdvisorContentTests checks the generated file matches the JSON."""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'Mobile', 'Coo.Mobile.Presentation', 'Advisor')
CONTENT = os.path.join(ROOT, 'Content')


def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def lst(items, indent):
    pad = ' ' * indent
    return '[\n' + ''.join(f'{pad}    {lit(i)},\n' for i in items) + f'{pad}]'


out = ['// <auto-generated>Made by eng/gen-advisor-content.py from Advisor/Content/*.json; edit the JSON, not this file.</auto-generated>',
       'namespace Coo.Mobile.Presentation.Advisor;', '',
       'internal static class AdvisorContentData', '{',
       '    public static readonly IReadOnlyDictionary<string, AdvisorContent> All = new Dictionary<string, AdvisorContent>(StringComparer.Ordinal)',
       '    {']
for name in sorted(os.listdir(CONTENT)):
    if not name.endswith('.json'):
        continue
    d = json.load(open(os.path.join(CONTENT, name), encoding='utf-8'))
    h = d['headings']
    out.append(f'        [{lit(name[:-5])}] = new(')
    out.append(f'            new AdvisorHeadings({lit(h["motor"])}, {lit(h["cognitive"])}, {lit(h["social"])}, {lit(h["rhythm"])}, {lit(h["tip"])}),')
    out.append('            [')
    for st in d['stages']:
        out.append(f'                new AdvisorStage(')
        out.append(f'                    {st["from"]},')
        out.append(f'                    {lit(st["badge"])},')
        out.append(f'                    {lit(st["summary"])},')
        for key in ['motor', 'cognitive', 'social', 'rhythm']:
            out.append(f'                    {lst(st[key], 20)},')
        out.append(f'                    {lit(st["tip"])}),')
    out.append('            ],')
    out.append('            [')
    for q in d['questions']:
        out.append(f'                new AdvisorQuestions({q["from"]}, {lst(q["items"], 16)}),')
    out.append('            ],')
    out.append(f'            {lst(d["fallback"], 12)}),')
out += ['    };', '}', '']
open(os.path.join(ROOT, 'AdvisorContentData.g.cs'), 'w', encoding='utf-8').write('\n'.join(out))
print('wrote AdvisorContentData.g.cs')
