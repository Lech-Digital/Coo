namespace Coo.Api.Infrastructure.Persistence;

// The EF Core shapes of the three tables (Spec 008 §4). They are storage only: no behaviour, never seen outside
// this folder. Domain objects are mapped to them by CareEntryStore, through the codecs.

/// <summary><c>entry_kind_versions</c>: every (kind, details version) the codecs can read (G3).</summary>
internal sealed class KindVersionRecord
{
    public required string Kind { get; init; }

    public required int Version { get; init; }
}

/// <summary><c>households</c>: the per-household <c>seq</c> counter (ADR 0002 §6).</summary>
internal sealed class HouseholdRecord
{
    public required Guid Id { get; init; }

    public long NextSeq { get; init; } = 1;

    public required DateTime CreatedAt { get; init; }
}

/// <summary><c>care_entries</c>: the core as columns, the details as <c>jsonb</c> (ADR 0010 §2).</summary>
internal sealed class CareEntryRecord
{
    public required Guid Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required string Kind { get; init; }

    public Guid? SubjectBabyId { get; init; }

    public string? SubjectPerson { get; init; }

    public required bool IsSession { get; init; }

    public required DateTime StartAt { get; init; }

    public required short StartOffsetMin { get; init; }

    public DateTime? EndAt { get; init; }

    public short? EndOffsetMin { get; init; }

    public required string LoggedBy { get; init; }

    public required string Source { get; init; }

    public string? SourcePromptVersion { get; init; }

    public string? Note { get; init; }

    public required string Details { get; init; }

    /// <summary>Generated by the database from <c>details-&gt;&gt;'v'</c>, never written by code.</summary>
    public int DetailsVersion { get; init; }

    public required long VersionWallMs { get; init; }

    public required int VersionCounter { get; init; }

    public required Guid VersionDevice { get; init; }

    public required bool IsDeleted { get; init; }

    public required long Seq { get; init; }
}
