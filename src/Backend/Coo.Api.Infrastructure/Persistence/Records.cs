using Microsoft.AspNetCore.Identity;

namespace Coo.Api.Infrastructure.Persistence;

// The EF Core shapes of the tables (Spec 008 §4). They are storage only: no behaviour, never seen outside
// this folder. Domain objects are mapped to them by CareEntryStore, through the codecs.

/// <summary><c>entry_kind_versions</c>: every (kind, details version) the codecs can read (G3).</summary>
internal sealed class KindVersionRecord
{
    public required string Kind { get; init; }

    public required int Version { get; init; }
}

/// <summary><c>households</c>: the per-household <c>seq</c> counter (ADR 0002 §6).</summary>
internal sealed class HouseholdRecord
{
    public required Guid Id { get; init; }

    public long NextSeq { get; init; } = 1;

    public required DateTime CreatedAt { get; init; }

    /// <summary>The Owner who created it (Spec 010 §4.2). Null for households created before sign-in existed.</summary>
    public Guid? CreatedBy { get; init; }
}

/// <summary><c>care_entries</c>: the core as columns, the details as <c>jsonb</c> (ADR 0010 §2).</summary>
internal sealed class CareEntryRecord
{
    public required Guid Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required string Kind { get; init; }

    public Guid? SubjectBabyId { get; init; }

    public string? SubjectPerson { get; init; }

    public required bool IsSession { get; init; }

    public required DateTime StartAt { get; init; }

    public required short StartOffsetMin { get; init; }

    public DateTime? EndAt { get; init; }

    public short? EndOffsetMin { get; init; }

    public required string LoggedBy { get; init; }

    public required string Source { get; init; }

    public string? SourcePromptVersion { get; init; }

    public string? Note { get; init; }

    public required string Details { get; init; }

    /// <summary>Generated by the database from <c>details-&gt;&gt;'v'</c>, never written by code.</summary>
    public int DetailsVersion { get; init; }

    public required long VersionWallMs { get; init; }

    public required int VersionCounter { get; init; }

    public required Guid VersionDevice { get; init; }

    public required bool IsDeleted { get; init; }

    public required long Seq { get; init; }
}

/// <summary>
/// <c>AspNetUsers</c> (ADR 0003 §3): ASP.NET Core Identity's user, with <c>Guid</c> keys and never a password. Only
/// what Spec 010 §4.2 allows is kept: the email (Identity's column), the display name, and the Google <c>sub</c> as the
/// login in <c>AspNetUserLogins</c>.
/// </summary>
internal sealed class CooUser : IdentityUser<Guid>
{
    public string DisplayName { get; set; } = "";
}

/// <summary><c>auth_nonces</c>: single-use sign-in nonces, by SHA-256 (Spec 010 §4.2).</summary>
internal sealed class AuthNonceRecord
{
    public required string NonceHash { get; init; }

    public required DateTime IssuedAt { get; init; }

    public DateTime? ConsumedAt { get; init; }
}

/// <summary><c>device_sessions</c>: one per phone per user; the current and the previous refresh token, by hash.</summary>
internal sealed class DeviceSessionRecord
{
    public required Guid Id { get; init; }

    public required Guid UserId { get; init; }

    public required Guid DeviceId { get; init; }

    public required string DeviceName { get; init; }

    public required string RefreshHash { get; init; }

    public string? PreviousRefreshHash { get; init; }

    public required DateTime CreatedAt { get; init; }

    public required DateTime LastUsedAt { get; init; }

    public DateTime? RevokedAt { get; init; }
}

/// <summary><c>memberships</c>: a user's role in a household (ADR 0003 §6). The role is <c>owner</c>, <c>parent</c> or <c>caregiver</c>.</summary>
internal sealed class MembershipRecord
{
    public required Guid HouseholdId { get; init; }

    public required Guid UserId { get; init; }

    public required string Role { get; init; }

    public required DateTime JoinedAt { get; init; }

    /// <summary>Set when the member is removed (Increment 11b); read by the membership check (Spec 011 §6.5).</summary>
    public DateTime? RevokedAt { get; init; }
}

/// <summary><c>baby_profiles</c> (Spec 011 §7.2): a synced record; <c>seq</c> from the household's counter.</summary>
internal sealed class BabyProfileRecord
{
    public required Guid Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required string Name { get; init; }

    public required List<string> Nicknames { get; init; }

    public DateOnly? BirthDate { get; init; }

    public DateOnly? DueDate { get; init; }

    public required long VersionWallMs { get; init; }

    public required int VersionCounter { get; init; }

    public required Guid VersionDevice { get; init; }

    public required bool IsDeleted { get; init; }

    public required long Seq { get; init; }
}

/// <summary><c>household_settings</c>: one per household, keyed by it (Spec 001 §5.3).</summary>
internal sealed class HouseholdSettingsRecord
{
    public required Guid HouseholdId { get; init; }

    public required string VolumeUnit { get; init; }

    public required string TimeZoneId { get; init; }

    public required List<string> HiddenKinds { get; init; }

    public required long VersionWallMs { get; init; }

    public required int VersionCounter { get; init; }

    public required Guid VersionDevice { get; init; }

    public required bool IsDeleted { get; init; }

    public required long Seq { get; init; }
}

/// <summary><c>duplicate_dismissals</c>: "keep both" decisions (Q6), the pair in canonical order.</summary>
internal sealed class DuplicateDismissalRecord
{
    public required Guid Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required Guid EntryA { get; init; }

    public required Guid EntryB { get; init; }

    public required long VersionWallMs { get; init; }

    public required int VersionCounter { get; init; }

    public required Guid VersionDevice { get; init; }

    public required bool IsDeleted { get; init; }

    public required long Seq { get; init; }
}

/// <summary><c>applied_changes</c>: the result of every decided change ID, for 30 days (ADR 0002 §5).</summary>
internal sealed class AppliedChangeRecord
{
    public required Guid ChangeId { get; init; }

    public required string Result { get; init; }

    public string? Reason { get; init; }

    public required DateTime AppliedAt { get; init; }
}

/// <summary><c>sync_conflicts</c>: both version stamps of a losing write (ruling 4), for 30 days.</summary>
internal sealed class SyncConflictRecord
{
    public long Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required Guid ChangeId { get; init; }

    public required string EntityType { get; init; }

    public required Guid EntityId { get; init; }

    public required long WinnerWallMs { get; init; }

    public required int WinnerCounter { get; init; }

    public required Guid WinnerDevice { get; init; }

    public required long LoserWallMs { get; init; }

    public required int LoserCounter { get; init; }

    public required Guid LoserDevice { get; init; }

    public required DateTime RecordedAt { get; init; }
}

/// <summary><c>consents</c> (Spec 011 §3, Q1): per account, with the wording version, provable (GDPR Art. 7(1)).</summary>
internal sealed class UserConsentRecord
{
    public required Guid UserId { get; init; }

    public required string Purpose { get; init; }

    public required string Wording { get; init; }

    public required DateTime GivenAt { get; init; }

    public string? AppVersion { get; init; }

    public string? Language { get; init; }
}

/// <summary><c>invitations</c> (Spec 011b §10.3): only the code's SHA-256 is kept; rows go within a day after they expire (the daily job).</summary>
internal sealed class InvitationRecord
{
    public required Guid Id { get; init; }

    public required Guid HouseholdId { get; init; }

    public required string Role { get; init; }

    public required string CodeHash { get; init; }

    public required Guid CreatedBy { get; init; }

    public required DateTime CreatedAt { get; init; }

    public required DateTime ExpiresAt { get; init; }

    public Guid? AcceptedBy { get; init; }

    public DateTime? AcceptedAt { get; init; }

    public DateTime? RevokedAt { get; init; }
}

/// <summary><c>subscriptions</c>: tracks household premium access via store purchases (Increment 12).</summary>
internal sealed class SubscriptionRecord
{
    public required string PurchaseToken { get; init; }

    public required Guid HouseholdId { get; init; }

    public required Guid UserId { get; init; }

    public required string ProductId { get; init; }

    public required string Status { get; set; }

    public required DateTime ExpiryDate { get; set; }

    public required DateTime CreatedAt { get; init; }

    public required DateTime UpdatedAt { get; set; }
}
